  let language = 'pt';

  function normalize(value) {
    return value === 'tet' ? 'tet' : 'pt';
  }

  function setLanguage(value) {
    language = normalize(value);
    if (typeof document !== 'undefined') {
      document.documentElement.lang = language === 'tet' ? 'tet' : 'pt-BR';
      document.documentElement.dataset.language = language;
    }
  }

  function getLanguage() {
    return language;
  }

  function translatePhrase(text) {
    if (language !== 'tet' || !text) return text;
    const direct = TETUN[text];
    if (direct) return direct;
    const reference = text.match(/^(\d+) referência$/);
    if (reference) return `${reference[1]} referénsia`;
    return text;
  }

  function t(text, variables) {
    let value = translatePhrase(text);
    if (variables) {
      for (const [key, replacement] of Object.entries(variables)) {
        value = value.split(`{${key}}`).join(String(replacement));
      }
    }
    return value;
  }

  const ATTRIBUTES = ['placeholder', 'title', 'aria-label', 'alt'];
  const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'CODE', 'PRE']);

  function localize(root) {
    if (language !== 'tet' || !root || typeof document === 'undefined') return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (SKIP.has(node.parentElement?.tagName)) return NodeFilter.FILTER_REJECT;
        return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    const textNodes = [];
    while (walker.nextNode()) textNodes.push(walker.currentNode);
    for (const node of textNodes) {
      const original = node.nodeValue;
      const trimmed = original.trim();
      const translated = translatePhrase(trimmed);
      if (translated !== trimmed) {
        node.nodeValue = original.replace(trimmed, translated);
      }
    }
    const elements = root.querySelectorAll ? [root, ...root.querySelectorAll('*')] : [root];
    for (const element of elements) {
      if (!element.getAttribute) continue;
      for (const name of ATTRIBUTES) {
        const value = element.getAttribute(name);
        if (!value) continue;
        const translated = translatePhrase(value.trim());
        if (translated !== value.trim()) element.setAttribute(name, translated);
      }
    }
  }

  if (typeof window !== 'undefined') {
    const params = new URLSearchParams(window.location.search);
    const stored = window.localStorage?.getItem('cite-language');
    setLanguage(params.get('lang') || stored || 'pt');
    if (document.body) localize(document.body);
    else document.addEventListener('DOMContentLoaded', () => localize(document.body), { once: true });
  }

  return { t, setLanguage, getLanguage, localize, messages: TETUN };
